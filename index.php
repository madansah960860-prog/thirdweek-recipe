        <h2>What the growing calendar says is cheap</h2>
        <p>Our seasonal guide follows the Northern Hemisphere and the typical United States harvest window, month by month, with notes on what tends to be cheapest at a farmers market.</p>
      </div>

      <div class="grid grid-5-7">
        <figure class="tile-frame" style="margin:0">
