      <div class="section-head">
        <span class="kicker">Method</span>
        <h2>How a recipe gets onto this site</h2>
        <p>Nothing here is published on the first attempt. Every recipe runs the same five steps before it gets an address, and the steps do not get shortened because a publishing date is close.</p>
      </div>

      <div class="grid grid-7-5">
        <div class="tile-panel">
          <h3>Our testing standard</h3>
          <ol>
            <li><strong>Draft and first cook.</strong> One cook, one pass, every ingredient weighed on a digital scale and written down in grams as it goes into the bowl.</li>
            <li><strong>Second cook, different hands.</strong> Somebody who did not write the recipe makes it from the text alone. Anywhere they hesitate, the text is wrong, not the cook.</li>
            <li><strong>Third cook, ordinary equipment.</strong> Supermarket ingredients, a 12-inch skillet, a home oven checked against a separate thermometer. Ovens read 25°F off more often than people expect.</li>
            <li><strong>Numbers locked.</strong> Pan size, rack position, temperature, total time and yield are recorded as tested, not as estimated. Timers start at the cold pan, with the chopping counted in.</li>
            <li><strong>Failure modes named.</strong> Whatever broke during testing goes into the recipe as a warning, placed in the step where it can still be prevented.</li>
          </ol>
          <p>A recipe that cannot pass step two does not go up. Eleven drafts were cut this year for that reason alone.</p>
        </div>

        <div>
          <figure class="tile-frame tile-frame--tight" style="margin:0 0 var(--sp-4)">
            <img src="https://images.unsplash.com/photo-1466637574441-749b8f19452f?w=700&h=520&fit=crop&q=80"
                 alt="A wooden cutting board holding halved avocado, eggs, cherry tomatoes, mushrooms, scallions and spinach beside a chef's knife."
                 width="700" height="520" loading="lazy" decoding="async">
          </figure>
          <div class="note">
            <h4>Why the grams are always there</h4>
            <p>A cup of all-purpose flour scooped straight from the bag can weigh 120 g or 155 g, depending on how hard you press. That spread is the difference between a tender cookie and a dry one. Cups stay on every recipe because most American kitchens work in cups, but the weight sits beside them, and the metric toggle converts the whole ingredient list at once.</p>
          </div>
        </div>
