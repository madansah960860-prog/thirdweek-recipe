        <h4>Three failures we name out loud</h4>
        <p>Weeknight cooking goes wrong in the same few places, so we write the fix into the step rather than leaving it for a comments section.</p>
        <ul>
          <li><strong>The crowded pan.</strong> Vegetables need space and dry air to brown. Two sheet pans at 425°F beat one packed pan in every side-by-side we have run.</li>
          <li><strong>Cold protein into a cold pan.</strong> Chicken and shrimp stick, tear and release water. Heat the pan, dry the surface of the protein, then cook.</li>
          <li><strong>Salt only at the end.</strong> Salt added in stages seasons the whole dish. Salt added at the table seasons the first bite and nothing under it.</li>
