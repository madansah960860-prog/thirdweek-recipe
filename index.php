        <div>
          <h3>September in most of the country</h3>
          <p>Late tomatoes, the first winter squash, sweet corn on its way out, apples on their way in, and peppers cheap enough to roast a full sheet pan at once.</p>
          <ul>
            <li><strong>Buy now:</strong> bell peppers, eggplant, tomatoes, sweet corn, green beans, apples, plums.</li>
            <li><strong>Arriving at the market:</strong> butternut and delicata squash, Brussels sprouts, sweet potatoes, leeks.</li>
            <li><strong>Freeze or preserve:</strong> roasted peppers in oil, tomato passata, blanched green beans.</li>
          </ul>
          <div class="note">
            <h4>Field note: what this looks like in Portland</h4>
            <p>Our own shopping happens within a mile of the kitchen, so treat the local detail as one region rather than a rule. Oregon tomatoes land late here and hold into early October, Hood River apples arrive in volume from mid September, and chanterelles turn up once the rain returns. If your market runs two or three weeks ahead of ours, trust the stall in front of you rather than the calendar.</p>
          </div>
